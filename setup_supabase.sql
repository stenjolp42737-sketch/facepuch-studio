-- FACEPUCH STUDIO 4.8: server-side tables and security policies
-- Run this in Supabase SQL Editor AFTER creating an owner in Authentication > Users.
-- Replace OWNER_USER_UUID below with the user's UUID from Authentication > Users.

create table if not exists public.site_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.site_messages (
  id bigint generated by default as identity primary key,
  name text not null default 'Гость',
  body text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.site_reviews (
  id bigint generated by default as identity primary key,
  name text not null default 'Гость',
  body text not null,
  blocked boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.site_admins enable row level security;
alter table public.site_messages enable row level security;
alter table public.site_reviews enable row level security;

-- Explicit SQL privileges (RLS policies below still decide which rows are visible).
grant usage on schema public to anon, authenticated;
grant select on public.site_admins to authenticated;
grant insert, update, delete on public.news to authenticated;
grant insert, update, delete on public.site_settings to authenticated;
grant insert on public.site_messages to anon, authenticated;
grant select on public.site_messages to authenticated;
grant insert on public.site_reviews to anon, authenticated;
grant select on public.site_reviews to anon, authenticated;
grant update, delete on public.site_reviews to authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

-- An authenticated user can only see their own admin membership row.
drop policy if exists "Admins read own membership" on public.site_admins;
create policy "Admins read own membership" on public.site_admins
for select to authenticated using (user_id = auth.uid());

-- News: public can read published posts; only listed admins can write.
drop policy if exists "Admins insert news" on public.news;
create policy "Admins insert news" on public.news for insert to authenticated
with check (exists (select 1 from public.site_admins a where a.user_id = auth.uid()));
drop policy if exists "Admins update news" on public.news;
create policy "Admins update news" on public.news for update to authenticated
using (exists (select 1 from public.site_admins a where a.user_id = auth.uid()))
with check (exists (select 1 from public.site_admins a where a.user_id = auth.uid()));
drop policy if exists "Admins delete news" on public.news;
create policy "Admins delete news" on public.news for delete to authenticated
using (exists (select 1 from public.site_admins a where a.user_id = auth.uid()));

-- Site settings: public read, admins write.
drop policy if exists "Admins insert site settings" on public.site_settings;
create policy "Admins insert site settings" on public.site_settings for insert to authenticated
with check (exists (select 1 from public.site_admins a where a.user_id = auth.uid()));
drop policy if exists "Admins update site settings" on public.site_settings;
create policy "Admins update site settings" on public.site_settings for update to authenticated
using (exists (select 1 from public.site_admins a where a.user_id = auth.uid()))
with check (exists (select 1 from public.site_admins a where a.user_id = auth.uid()));
drop policy if exists "Admins delete site settings" on public.site_settings;
create policy "Admins delete site settings" on public.site_settings for delete to authenticated
using (exists (select 1 from public.site_admins a where a.user_id = auth.uid()));

-- Visitors may submit feedback/messages. Messages are readable only by admins.
drop policy if exists "Visitors submit messages" on public.site_messages;
create policy "Visitors submit messages" on public.site_messages for insert to anon, authenticated with check (true);
drop policy if exists "Admins read messages" on public.site_messages;
create policy "Admins read messages" on public.site_messages for select to authenticated
using (exists (select 1 from public.site_admins a where a.user_id = auth.uid()));
drop policy if exists "Visitors submit reviews" on public.site_reviews;
create policy "Visitors submit reviews" on public.site_reviews for insert to anon, authenticated with check (true);
drop policy if exists "Public read visible reviews" on public.site_reviews;
create policy "Public read visible reviews" on public.site_reviews for select to anon, authenticated using (blocked = false);
drop policy if exists "Admins read all reviews" on public.site_reviews;
create policy "Admins read all reviews" on public.site_reviews for select to authenticated
using (exists (select 1 from public.site_admins a where a.user_id = auth.uid()));
drop policy if exists "Admins update reviews" on public.site_reviews;
create policy "Admins update reviews" on public.site_reviews for update to authenticated
using (exists (select 1 from public.site_admins a where a.user_id = auth.uid()))
with check (exists (select 1 from public.site_admins a where a.user_id = auth.uid()));
drop policy if exists "Admins delete reviews" on public.site_reviews;
create policy "Admins delete reviews" on public.site_reviews for delete to authenticated
using (exists (select 1 from public.site_admins a where a.user_id = auth.uid()));

-- Storage: public downloads, owner-only uploads/replacements/deletions.
drop policy if exists "Public can view site media" on storage.objects;
create policy "Public can view site media" on storage.objects for select to anon, authenticated
using (bucket_id = 'site-media');
drop policy if exists "Admins upload site media" on storage.objects;
create policy "Admins upload site media" on storage.objects for insert to authenticated
with check (bucket_id = 'site-media' and exists (select 1 from public.site_admins a where a.user_id = auth.uid()));
drop policy if exists "Admins update site media" on storage.objects;
create policy "Admins update site media" on storage.objects for update to authenticated
using (bucket_id = 'site-media' and exists (select 1 from public.site_admins a where a.user_id = auth.uid()))
with check (bucket_id = 'site-media' and exists (select 1 from public.site_admins a where a.user_id = auth.uid()));
drop policy if exists "Admins delete site media" on storage.objects;
create policy "Admins delete site media" on storage.objects for delete to authenticated
using (bucket_id = 'site-media' and exists (select 1 from public.site_admins a where a.user_id = auth.uid()));

